/** How sure a screenshot-sourced row's import is, and why */
function rowConfidence(
  row: ReviewRow,
  teamByKey: Map<string, ScreenshotTeam>,
  nameMatches: Map<string, NameMatch>
): { score: number; details: string[] } | null {
  const team = row.teamKey ? teamByKey.get(row.teamKey) : undefined;
  if (!team) return null;
  // A team picked by hand for the row needs no name match
  const match = row.autoMatched ? nameMatches.get(team.key) : undefined;
  const weakest = weakestSlot(team);
  const name = !row.autoMatched
    ? "team picked by hand"
    : !match
      ? ""
      : match.via === "dracoviz"
        ? "name matched through Dracoviz"
        : match.edits === 0
          ? "exact name"
          : `name ${match.edits} letter${match.edits !== 1 ? "s" : ""} off`;
  return {
    score: importConfidence(team, match),
    details: [`lowest tile ${Math.round(weakest.confidence * 100)}%`, name].filter(Boolean),
  };
}

/** Row positions ordered least confident first; rows without a team go last */
function confidenceOrder(
  rows: ReviewRow[],
  teamByKey: Map<string, ScreenshotTeam>,
  nameMatches: Map<string, NameMatch>
): number[] {
  return rows
    .map((row, index) => ({ index, score: rowConfidence(row, teamByKey, nameMatches)?.score ?? 2 }))
    .sort((a, b) => a.score - b.score || a.index - b.index)
    .map((item) => item.index);
}

/** The flag a screenshot-sourced row imports with: a known flag, else the overlay's country */
function screenshotFlag(row: ReviewRow, teamByKey: Map<string, ScreenshotTeam>): string {
  const known = getFlagsForPlayer(displayName(row.entry));
  if (known) return known.join(" ");
  const country = row.teamKey ? teamByKey.get(row.teamKey)?.country : null;
  return country ? normalizeCountryCode(country) : "-";
}

/** How sure a row's import is, as a chip with the reasons beside it */
function ConfidenceNote({ confidence }: { confidence: ReturnType<typeof rowConfidence> }) {
  if (!confidence) return null;
  const low = confidence.score < LOW_CONFIDENCE;
  return (
    <span className="flex items-center gap-1.5 text-xs">
      <span
        className={cn(
          "rounded px-1.5 py-0.5 font-medium",
          low ? "bg-amber-500/15 text-amber-800 dark:text-amber-300" : "bg-muted text-muted-foreground"
        )}
      >
        {Math.round(confidence.score * 100)}% sure
      </span>
      <span className="text-muted-foreground">{confidence.details.join(" · ")}</span>
    </span>
  );
}

